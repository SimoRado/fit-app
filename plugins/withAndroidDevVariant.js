const { withFinalizedMod } = require('expo/config-plugins');
const fs = require('node:fs');
const path = require('node:path');

/**
 * Makes the local debug APK ("Cubyfit Dev") installable next to the release
 * preview APK instead of replacing it.
 *
 *   release (preview)  com.bettereveryday.fitness      betterday://
 *   debug   (dev)      com.bettereveryday.fitness.dev  betterday-dev://
 *
 * The OAuth scheme must differ: if both apps registered betterday://, Android
 * could hand the Clerk callback to the wrong app or show a chooser. The JS side
 * derives the same scheme from the installed application ID (src/core/appVariant.ts).
 *
 * This runs as a finalized mod so it sees the manifest after every other plugin
 * (scheme, Clerk, dev-client) has written its intent filters. Each edit throws if
 * its anchor is missing, so a changed template fails the build loudly instead of
 * silently producing two apps that fight over the same callback.
 */
const DEV_SUFFIX = '.dev';
const DEV_LABEL = 'Cubyfit Dev';
const MARKER = '// Cubyfit: separate dev-client package';

// Replaces every literal occurrence with one placeholder. A later non-clean
// prebuild re-adds the literal scheme next to an existing placeholder, so the
// literal is always removed, not only on the first run.
function placeholderData(contents, pattern, placeholder, required) {
  const tag = `<data android:scheme="${placeholder}"/>`;
  const hasPlaceholder = contents.includes(tag);
  let inserted = hasPlaceholder;
  const next = contents.replace(new RegExp(`[ \\t]*${pattern}\\r?\\n?`, 'g'), match => {
    if (inserted) return '';
    inserted = true;
    return match.replace(new RegExp(pattern), tag);
  });
  if (required && !inserted) throw new Error(`withAndroidDevVariant: manifest has no scheme matching ${pattern}`);
  return next;
}

function transformManifest(contents, scheme) {
  const escaped = scheme.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  let next = placeholderData(contents, `<data android:scheme="${escaped}"/>`, '${cubyfitScheme}', true);
  // The dev-launcher QR scheme is only meaningful in the dev client. Release
  // gets a duplicate of its own scheme so scanning a dev QR never offers it.
  next = placeholderData(next, '<data android:scheme="exp\\+[^"$]+"/>', '${cubyfitDevClientScheme}', false);
  // Clerk's hosted-auth callback is keyed by package name; follow the real one.
  return next.replace(/android:host="[^"$]+\.hosted-callback"/g, 'android:host="${applicationId}.hosted-callback"');
}

function transformBuildGradle(contents, scheme, devClientScheme) {
  if (contents.includes(MARKER)) return contents;
  const defaultConfig = /defaultConfig \{\n/;
  const debugType = /buildTypes \{\n(\s*)debug \{\n/;
  if (!defaultConfig.test(contents)) throw new Error('withAndroidDevVariant: build.gradle has no defaultConfig block');
  if (!debugType.test(contents)) throw new Error('withAndroidDevVariant: build.gradle has no debug build type');
  return contents
    .replace(defaultConfig, match => `${match}        ${MARKER} (release values)\n        manifestPlaceholders.putAll([cubyfitScheme: '${scheme}', cubyfitDevClientScheme: '${scheme}'])\n`)
    .replace(debugType, (match, indent) => `${match}${indent}    ${MARKER}\n${indent}    applicationIdSuffix '${DEV_SUFFIX}'\n${indent}    manifestPlaceholders.putAll([cubyfitScheme: '${scheme}-dev', cubyfitDevClientScheme: '${devClientScheme}'])\n`);
}

function devStringsXml() {
  return `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by plugins/withAndroidDevVariant.js -->\n<resources>\n  <string name="app_name">${DEV_LABEL}</string>\n</resources>\n`;
}

function withAndroidDevVariant(config) {
  return withFinalizedMod(config, ['android', async config => {
    const appRoot = path.join(config.modRequest.platformProjectRoot, 'app');
    const scheme = Array.isArray(config.scheme) ? config.scheme[0] : config.scheme;
    if (typeof scheme !== 'string' || !scheme) throw new Error('withAndroidDevVariant: expo.scheme is required');
    const devClientScheme = `exp+${config.slug}`;

    const manifestPath = path.join(appRoot, 'src', 'main', 'AndroidManifest.xml');
    fs.writeFileSync(manifestPath, transformManifest(fs.readFileSync(manifestPath, 'utf8'), scheme));

    const gradlePath = path.join(appRoot, 'build.gradle');
    fs.writeFileSync(gradlePath, transformBuildGradle(fs.readFileSync(gradlePath, 'utf8'), scheme, devClientScheme));

    const stringsDir = path.join(appRoot, 'src', 'debug', 'res', 'values');
    fs.mkdirSync(stringsDir, { recursive: true });
    fs.writeFileSync(path.join(stringsDir, 'strings.xml'), devStringsXml());
    return config;
  }]);
}

module.exports = withAndroidDevVariant;
module.exports.transformManifest = transformManifest;
module.exports.transformBuildGradle = transformBuildGradle;
module.exports.DEV_SUFFIX = DEV_SUFFIX;
